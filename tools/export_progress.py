"""Export the Port Atlas state to files GitHub can show.

Writes PROGRESS.md (milestones, red/green scope blocks per subsystem, verified
scopes with their evidence) and progress/progress.svg (the block grid as an image
for the README). Uses the same StateBuilder as tools/port_map_server.py, so the
GitHub view and the local Atlas apply identical rules: a block is green only when
its evidence is verified, hash-matching and blocker-free.

Usage:  .venv\\Scripts\\python.exe tools\\export_progress.py [--root DIR] [--check]
--check exits 1 if the committed files are out of date (no writes).
"""

import argparse
import json
import sys
from collections import OrderedDict
from pathlib import Path
from xml.sax.saxutils import escape

sys.path.insert(0, str(Path(__file__).resolve().parent))
import port_map_server  # noqa: E402

GROUP_ORDER = [
    "Boot & recovery", "Platform", "Display & input", "Graphics",
    "Radio & network", "Audio & cameras", "Sensors & power", "Desktop",
]
STATE_ICON = {"done": "✅", "in-progress": "🟡", "blocked": "⛔", "not-started": "⬜"}
STATE_WORD = {"done": "Done", "in-progress": "In progress", "blocked": "Blocked", "not-started": "Not started"}
GREEN, RED = "🟩", "🟥"
PER_ROW = 40


def load(root):
    state = port_map_server.StateBuilder(root).get_state()
    milestones_path = Path(root) / "progress" / "milestones.json"
    milestones = json.loads(milestones_path.read_text(encoding="utf-8"))["milestones"]
    groups = OrderedDict((g, []) for g in GROUP_ORDER)
    for item in state["items"]:
        groups.setdefault(port_map_server.map_group(item["group"]), []).append(item)
    for items in groups.values():
        items.sort(key=lambda i: (i["state"] != "ready", i["kind"], i["label"].lower()))
    return state, milestones, groups


def render_markdown(state, milestones, groups):
    items = state["items"]
    ready = [i for i in items if i["state"] == "ready"]
    hardware = [i for i in items if i["kind"] == "hardware"]
    hw_ready = sum(1 for i in hardware if i["state"] == "ready")
    out = [
        "# NX809J port progress",
        "",
        "_Generated by `tools/export_progress.py` from the same data as the local Port Atlas. "
        "Do not edit by hand; it is rebuilt on every commit._",
        "",
        "**How to read this:** each small square is one piece of the port that has to be understood or proven. "
        f"{GREEN} means its stated scope is verified by evidence on file (hash-checked). "
        f"{RED} means it is still open. Green never means \"works on the phone\" unless the scope says so.",
        "",
        "| | Count |",
        "|---|---|",
        f"| {GREEN} Verified scopes | **{len(ready)}** |",
        f"| {RED} Open scopes | **{len(items) - len(ready)}** |",
        f"| Phone hardware tests passed | **{hw_ready} / {len(hardware)}** |",
        "",
        "## Milestones",
        "",
        "| # | Milestone | State | Where it stands |",
        "|---|---|---|---|",
    ]
    for m in milestones:
        links = ", ".join(f"[{Path(p).name}]({p})" for p in m.get("evidence", []))
        out.append(f"| {m['id']} | {m['title']} | {STATE_ICON[m['state']]} {STATE_WORD[m['state']]} | "
                   f"{m['now']} ({links}) |")
    out += ["", "## Scope map by subsystem", ""]
    for group, members in groups.items():
        if not members:
            continue
        g = sum(1 for i in members if i["state"] == "ready")
        out.append(f"**{group}** · {g} verified / {len(members)}")
        out.append("")
        squares = [GREEN if i["state"] == "ready" else RED for i in members]
        for start in range(0, len(squares), PER_ROW):
            out.append("".join(squares[start:start + PER_ROW]) + "  ")
        out.append("")
    out += ["## Verified scopes and their evidence", "",
            "| Subsystem | Scope | Evidence (SHA-256) |", "|---|---|---|"]
    for group, members in groups.items():
        for i in members:
            if i["state"] != "ready":
                continue
            ev = "<br>".join(
                f"[{e['path']}]({e['path']}) `{(e.get('sha256') or '')[:12]}`"
                for e in i.get("evidence", []) if e.get("path"))
            out.append(f"| {group} | **{i['label']}**: {i['scope']} | {ev} |")
    errors = [e for e in (state.get("errors") or []) if not e.startswith("backup")]
    if errors:
        out += ["", "**Open warnings:** " + "; ".join(errors)]
    out += ["", f"_Data generated {state['generated_at']}._", ""]
    return "\n".join(out)


def render_svg(groups):
    cell, gap, label_w, per_row = 10, 2, 150, 60
    rows = []
    y = 34
    for group, members in groups.items():
        if not members:
            continue
        lines = (len(members) + per_row - 1) // per_row
        rows.append((group, members, y))
        y += lines * (cell + gap) + 14
    width = label_w + per_row * (cell + gap) + 10
    total = sum(len(m) for m in groups.values())
    ready = sum(1 for m in groups.values() for i in m if i["state"] == "ready")
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{y + 6}" '
        f'viewBox="0 0 {width} {y + 6}" font-family="Segoe UI,Helvetica,Arial,sans-serif">',
        f'<rect width="100%" height="100%" rx="8" fill="#0d1117"/>',
        f'<text x="10" y="20" font-size="13" fill="#e6edf3" font-weight="600">NX809J port scopes: '
        f'{ready} verified / {total}</text>',
    ]
    for group, members, top in rows:
        parts.append(f'<text x="10" y="{top + 9}" font-size="11" fill="#9da7b3">{escape(group)}</text>')
        for idx, item in enumerate(members):
            cx = label_w + (idx % per_row) * (cell + gap)
            cy = top + (idx // per_row) * (cell + gap)
            fill = "#2ea043" if item["state"] == "ready" else "#da3633"
            parts.append(f'<rect x="{cx}" y="{cy}" width="{cell}" height="{cell}" rx="2" fill="{fill}">'
                         f'<title>{escape(item["label"])}</title></rect>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def _strip_volatile(text):
    return "\n".join(l for l in text.splitlines() if not l.startswith("_Data generated"))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    root = Path(args.root)
    state, milestones, groups = load(root)
    outputs = {
        root / "PROGRESS.md": render_markdown(state, milestones, groups),
        root / "progress" / "progress.svg": render_svg(groups),
    }
    stale = []
    for path, text in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old is None or _strip_volatile(old) != _strip_volatile(text):
            stale.append(path)
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check:
        for p in stale:
            print("out of date:", p.relative_to(root))
        return 1 if stale else 0
    print("updated:" if stale else "unchanged:", ", ".join(p.relative_to(root).as_posix() for p in outputs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
